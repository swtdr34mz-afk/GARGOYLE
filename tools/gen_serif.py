"""FIKH-S: the engraved serif faces of the panel (Liberation Serif Bold, SIL OFL 1.1, fonts/) as a C header,
in fm1-base's font format (tools/gen_font.py: anti-aliased, 16 alpha steps, untrimmed glyphs), so device/gfx.c's
cv_text draws them like its own.

    python3 tools/gen_serif.py            -> ui_serif.h (committed: the build does not run this)
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
os.environ["X0X_FONT_DIRS"] = str(ROOT / "fonts")
os.environ.pop("FM1_FONT_TRIM", None)
os.environ.pop("FM1_FONT_PACK", None)
sys.path.insert(0, str(ROOT / "fm1-base" / "tools"))
import gen_font  # noqa: E402

# (name, px, first, last): capitals, digits and signs only (the panel's labels are all capitals)
FACES = [("SERIF_XS", 9, 32, 95),    # the small print: units, footers
         ("SERIF_S", 11, 32, 95),    # the labels under the knobs (WARP, SPAN ...)
         ("SERIF_M", 14, 32, 95),    # the page, the algorithm's name
         ("SERIF_L", 22, 32, 95),    # the title
         ("SERIF_XL", 30, 32, 95)]   # the big readout


def main():
    out = ["/* generated by tools/gen_serif.py: Liberation Serif Bold (SIL OFL 1.1, fonts/LiberationSerif-OFL.txt) */",
           "#pragma once", ""]
    total = 0
    for name, px, first, last in FACES:
        h, glyphs = gen_font.render("LiberationSerif-Bold.ttf", px, 1, False, first, last)
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536
        total += len(data)
        out.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        out.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};")
        out.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};")
        out.append(f"static const felucca_font_t FONT_{name} = {{ {h}, {gen_font.PAD}, {first}, {last}, "
                   f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        out.append("")
        print(f"{name}: {px}px, h {h}, {len(data)} B")
    (ROOT / "ui_serif.h").write_text("\n".join(out))
    print(f"ui_serif.h: {total} B")


if __name__ == "__main__":
    main()
